import { defineSchema, defineTable } from 'convex/server';
import { v } from 'convex/values';

export default defineSchema({
  accounts: defineTable({
    clerkId: v.string(),
    email: v.string(),
    role: v.union('buyer', 'seller'),
    fullName: v.string(),
    companyName: v.string(),
    createdAt: v.number(),
  }).index('by_email', ['email']),

  equipment: defineTable({
    sku: v.string(),
    name: v.string(),
    category: v.union('POWER', 'DEWATERING', 'HYDRAULIC', 'LIGHTING', 'CUTTING', 'AIR'),
    imageUrl: v.string(),
    conditionRating: v.union('GRADE-A1', 'GRADE-A2'),
    availabilityFlag: v.union('IN VEHICLE', 'DEPOT READY'),
    emergencyHourlyRate: v.number(),
    emergencyDispatchFee: v.number(),
    rentalDailyRate: v.number(),
    rentalWeeklyRate: v.number(),
    purchasePrice: v.number(),
    stockQty: v.number(),
    sellerId: v.string(),
    sellerName: v.string(),
    depositAmount: v.number(),
    depositTier: v.union('TIER-1 BOND', 'TIER-2 BOND'),
    rating: v.number(),
    lastPingSeconds: v.number(),
    distanceMiles: v.number(),
    etaMinutes: v.number(),
    nodeId: v.string(),
    nodeCallsign: v.string(),
    courierName: v.string(),
    courierPlate: v.string(),
    weightLbs: v.number(),
    primaryOutput: v.string(),
    voltageOrPressure: v.string(),
    inspectionDate: v.string(),
    summary: v.string(),
    specs: v.object({}),
    checklist: v.object({}),
    createdAt: v.number(),
  }),

  orders: defineTable({
    poNumber: v.string(),
    buyerId: v.string(),
    buyerCompany: v.string(),
    gstin: v.string(),
    deliveryAddress: v.string(),
    deliveryTier: v.union('FREIGHT', 'ER_DROP', 'PICKUP'),
    deliveryFee: v.number(),
    subtotal: v.number(),
    gstAmount: v.number(),
    grandTotal: v.number(),
    status: v.union('PENDING_APPROVAL', 'APPROVED_FOR_RELEASE', 'IN_TRANSIT', 'DELIVERED', 'CANCELLED_BY_BUYER', 'CANCELLED_BY_SELLER'),
    createdAt: v.number(),
    cancelledAt: v.maybe(v.number()),
    cancelledBy: v.union('BUYER', 'SELLER'),
    cancellationReason: v.maybe(v.string()),
    items: v.array(
      defineTable({
        equipmentId: v.string(),
        sku: v.string(),
        name: v.string(),
        sellerId: v.string(),
        sellerName: v.string(),
        qty: v.number(),
        unitPrice: v.number(),
        totalPrice: v.number(),
      })
    ),
    createdAt: v.number(),
  }),

  missions: defineTable({
    missionCode: v.string(),
    buyerId: v.string(),
    buyerName: v.string(),
    equipmentId: v.string(),
    mode: v.union('emergency', 'rental'),
    dropZoneAddress: v.string(),
    siteCoordinates: v.maybe(v.string()),
    priorityOverride: v.boolean(),
    etaTotalSeconds: v.number(),
    remainingSeconds: v.number(),
    status: v.union('VERIFIED', 'LOADED', 'EN_ROUTE', 'ARRIVED', 'COMPLETED', 'ABORTED'),
    handoffPin: v.maybe(v.string()),
    courierName: v.maybe(v.string()),
    courierPlate: v.maybe(v.string()),
    startedAt: v.maybe(v.string()),
    totalCost: v.number(),
    rentalDays: v.number(),
    cancellationReason: v.maybe(v.string()),
    logs: v.array(v.string()),
    createdAt: v.number(),
  }),

  depotNodes: defineTable({
    callsign: v.string(),
    region: v.string(),
    status: v.string(),
    sellerId: v.string(),
    leadTech: v.maybe(v.string()),
    createdAt: v.number(),
  }),
});